// Regenerates src/psl_icann.ts and src/psl_private.ts from public_suffix_list.dat at a pinned
// commit of https://github.com/publicsuffix/list. Usage: `node scripts/update-psl.mjs [commit]`.
// The commit is recorded in both file headers; review the diff before committing (docs/oauth-relay.md).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PINNED = "9dfbe81931367b3f0af21035c36ae7eeb830dd88";
const commit = process.argv[2] ?? PINNED;
if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error("the commit must be a 40-character sha");

const url = `https://raw.githubusercontent.com/publicsuffix/list/${commit}/public_suffix_list.dat`;
const response = await fetch(url);
if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
const text = await response.text();

const sections = { icann: [], private: [] };
const wildcards = { icann: [], private: [] };
let current = null;
for (const raw of text.split("\n")) {
  const line = raw.trim();
  if (line.startsWith("// ===BEGIN ICANN DOMAINS===")) current = "icann";
  else if (line.startsWith("// ===BEGIN PRIVATE DOMAINS===")) current = "private";
  else if (line.startsWith("// ===END")) current = null;
  else if (current && line && !line.startsWith("//")) {
    const rule = line.split(/\s/)[0];
    // Only ASCII names are valid hosts (validate.ts), so an IDN rule can never match. A wildcard
    // rule `*.x.y` is kept as its base `x.y`: everything below it is a public suffix. An exception
    // rule (`!www.ck`) is dropped, which only makes the relay stricter.
    if (rule.startsWith("*.") && /^[a-z0-9.-]+$/.test(rule.slice(2))) wildcards[current].push(rule.slice(2));
    else if (!rule.startsWith("*") && !rule.startsWith("!") && /^[a-z0-9.-]+$/.test(rule)) {
      sections[current].push(rule);
    }
  }
}

function emit(name, exportName, doc, rules, wildcardRules) {
  const list = (items) => [...new Set(items)].sort().map((rule) => `  "${rule}",`).join("\n");
  const source =
    `// GENERATED by scripts/update-psl.mjs -- do not edit by hand.\n` +
    `// Source: https://github.com/publicsuffix/list/blob/${commit}/public_suffix_list.dat\n` +
    `// ${doc}\n` +
    `export const ${exportName}: ReadonlySet<string> = new Set([\n${list(rules)}\n]);\n` +
    `// Bases of wildcard rules: every name below one of these is a public suffix.\n` +
    `export const ${exportName}_WILDCARD_BASES: ReadonlySet<string> = new Set([\n${list(wildcardRules)}\n]);\n`;
  writeFileSync(fileURLToPath(new URL(`../src/${name}`, import.meta.url)), source);
  console.log(`${name}: ${new Set(rules).size} rules`);
}

emit("psl_icann.ts", "PSL_ICANN", "ICANN section: public suffixes such as co.uk.", sections.icann, wildcards.icann);
emit(
  "psl_private.ts",
  "PSL_PRIVATE",
  "Private section: hosting providers whose customers share a suffix (github.io, pages.dev, ...).",
  sections.private,
  wildcards.private,
);
